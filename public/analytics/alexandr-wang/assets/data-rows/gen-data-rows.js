// node gen-data-rows.js -> data-rows.js: the shared\data.js rows the hero boards need, built from 02-research\ledger.json the way
// style-frames\gen-figures.js builds the style frames' figures. v, unit, tier, asOf and on (the ledger's date) are the ledger's own,
// verbatim; display is printed from v by one rule per row (dp below), never typed. Ive writes this file; Davinci merges it into
// shared\data.js (his territory), sources and figures by key. Fails on a missing key.
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '../../..') + '/';            // videos/alexandr-wang/
const L = JSON.parse(fs.readFileSync(ROOT + '02-research/ledger.json', 'utf8'));
const idx = Object.fromEntries(L.map(r => [r.key, r]));

const SOURCES = {
  meta_q2_2026:  { name: 'Meta Q2 2026 earnings release', tier: 'P' },
  sp_global:     { name: 'S&P Global Market Intelligence via StockAnalysis', tier: 'E' }
};
// [key, source id, how it prints: usdB with n decimals, or usdM]
const ROWS = [
  // H11 The bill: the full year
  ['meta_capex_guide_2026_jul_low',  'meta_q2_2026', ['usdB', 0]],
  ['meta_capex_guide_2026_jul_high', 'meta_q2_2026', ['usdB', 0]],
  ['meta_rev_consensus_fy2026',      'sp_global',    ['usdB', 1]],
  // H11 The bill: Q2 2026
  ['meta_revenue_q2_2026', 'meta_q2_2026', ['usdB', 2]],
  ['meta_ocf_q2_2026',     'meta_q2_2026', ['usdB', 2]],
  ['meta_capex_q2_2026',   'meta_q2_2026', ['usdB', 2]],
  ['meta_fcf_q2_2026',     'meta_q2_2026', ['usdM', 0]]
];
const print = ([f, dp], v) => f === 'usdB' ? '$' + (v / 1e9).toFixed(dp) + 'B' : '$' + Math.round(v / 1e6) + 'M';

let out = `/* Rows for shared\\data.js, GENERATED by dashboards\\assets\\data-rows\\gen-data-rows.js from 02-research\\ledger.json
   (${L.length} rows, read ${new Date().toISOString().slice(0, 10)}). v, unit, tier, asOf, on: the ledger's value, unit, tier,
   as_of and date, verbatim (v in the ledger's unit: USD, not $B). display is printed from v. Merge by key. */
const BW_ROWS = {
  sources: {\n`;
for (const [k, s] of Object.entries(SOURCES)) out += `    ${k}: ${JSON.stringify(s)},\n`;
out += `  },\n  figures: {\n`;
for (const [k, src, p] of ROWS) {
  const r = idx[k]; if (!r) throw new Error('not in ledger: ' + k);
  if (SOURCES[src].tier !== r.tier) throw new Error(`${k}: ledger tier ${r.tier}, source tier ${SOURCES[src].tier}`);
  const f = { v: r.value, unit: r.unit, display: print(p, r.value), tier: r.tier, src, asOf: r.as_of, on: r.date };
  out += `    ${k}: ${JSON.stringify(f)},\n`;
}
out += `  }\n};\nif (typeof module !== 'undefined') module.exports = BW_ROWS;\n`;
fs.writeFileSync(path.join(__dirname, 'data-rows.js'), out);
console.log('wrote', ROWS.length, 'rows');
