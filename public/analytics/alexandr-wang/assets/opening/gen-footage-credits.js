// node gen-footage-credits.js -> footage-credits.js: the footage credits 22-the-path prints, embedded at build time from the layout's
// record (spec\credits.json, written by scripts\layout.py from the deliveries' attributions), so the page needs no request at render
// time (a synchronous file:// XHR can come back empty under capture). Re-run whenever the layout rewrites credits.json.
// Fails on a missing plate, so a renamed credit can never render blank.
const fs = require('fs'), path = require('path');
const SPEC = path.resolve(__dirname, '../../../spec/credits.json');
const WANT = ['frame-credit-03-meta-datacenter-hyperion', 'frame-credit-win-b005'];
const plates = JSON.parse(fs.readFileSync(SPEC, 'utf8')).plates || [];
const out = {};
for (const n of WANT) { const p = plates.find(x => x.name === n); if (!p || !p.text) throw new Error('no footage credit ' + n + ' in spec/credits.json'); out[n] = p.text; }
fs.writeFileSync(path.join(__dirname, 'footage-credits.js'),
  `/* GENERATED by gen-footage-credits.js from spec\\credits.json (${new Date().toISOString().slice(0, 10)}); do not edit by hand. */\n` +
  `const FOOTAGE_CREDITS = ${JSON.stringify(out, null, 1)};\n`);
console.log('wrote', Object.keys(out).length, 'credits');
